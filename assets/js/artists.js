// Resolve to a clickable URL: web link if present, else Instagram, else null.
export function artistUrl(name) {
  const a = ARTISTS[name];
  if (!a) return null;
  if (a.web) return a.web;
  if (a.instagram) return `https://instagram.com/${a.instagram.replace(/^@/, "")}`;
  return null;
}
